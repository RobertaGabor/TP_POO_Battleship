package views;

public class SubmarinoView {
     private int x;
    private int y;
    private int ancho;
    private int alto;

    public SubmarinoView(int x, int y, int ancho, int alto) {
        this.x = x;
        this.y = y;
        this.ancho = ancho;
        this.alto = alto;
        
    }

    public int getX() { return x; }
    public int getY() { return y; }

}
